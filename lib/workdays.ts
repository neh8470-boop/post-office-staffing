// 연간 근무일수 = 그 해 연간 총 일수 − 공제일수(토·일요일 + 공휴일(대체공휴일 포함))
// 공휴일은 법정 공휴일 기준으로 직접 적은 값이다. 실제 기준과 다르면 이 목록만 고치면 된다.

// 계산에 쓰는 기준 연도. 업무량·모수 자료가 2025년 값이라 같은 해(2025년)의 근무일수를 쓴다.
// (담당자 산출 파일도 2025년 기준 244일을 쓴다. 자료 연도가 바뀌면 이 값만 바꾸면 된다.)
export const WORK_YEAR = 2025;

export const HOLIDAYS: Record<number, string[]> = {
  2025: [
    "2025-01-01", // 신정
    "2025-01-27", // 임시공휴일
    "2025-01-28", "2025-01-29", "2025-01-30", // 설날 연휴
    "2025-03-01", "2025-03-03", // 삼일절(토요일) + 대체공휴일
    "2025-05-05", "2025-05-06", // 어린이날·부처님오신날(같은 날) + 대체공휴일
    "2025-06-03", // 대통령선거일
    "2025-06-06", // 현충일
    "2025-08-15", // 광복절
    "2025-10-03", // 개천절
    "2025-10-05", "2025-10-06", "2025-10-07", "2025-10-08", // 추석 연휴 + 대체공휴일
    "2025-10-09", // 한글날
    "2025-12-25", // 성탄절
  ],
  2026: [
    "2026-01-01", // 신정
    "2026-02-16", "2026-02-17", "2026-02-18", // 설날 연휴
    "2026-03-01", "2026-03-02", // 삼일절(일요일) + 대체공휴일
    "2026-05-05", // 어린이날
    "2026-05-24", "2026-05-25", // 부처님오신날(일요일) + 대체공휴일
    "2026-06-03", // 지방선거일
    "2026-06-06", // 현충일(토요일, 대체공휴일 없음)
    "2026-08-15", "2026-08-17", // 광복절(토요일) + 대체공휴일
    "2026-09-24", "2026-09-25", "2026-09-26", // 추석 연휴
    "2026-10-03", "2026-10-05", // 개천절(토요일) + 대체공휴일
    "2026-10-09", // 한글날
    "2026-12-25", // 성탄절
  ],
};

export function countWorkdays(year: number = WORK_YEAR): number {
  const holidaySet = new Set(HOLIDAYS[year] ?? []);
  let count = 0;
  for (let d = new Date(Date.UTC(year, 0, 1)); d.getUTCFullYear() === year; d.setUTCDate(d.getUTCDate() + 1)) {
    const day = d.getUTCDay(); // 0 일요일, 6 토요일
    const iso = d.toISOString().slice(0, 10);
    if (day !== 0 && day !== 6 && !holidaySet.has(iso)) count += 1;
  }
  return count;
}
